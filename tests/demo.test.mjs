import assert from 'node:assert/strict';
import {initialDebts, outstanding, debtTotal, visibleDebts, confirmPayment, receiptHtml} from '../src/app/demo.mjs';
const debts=initialDebts();
assert.equal(debtTotal(outstanding(debts)),847.5);
assert.deepEqual(visibleDebts(debts,'Vencido').map(d=>d.id),['predial']);
assert.equal(visibleDebts(debts).at(-1).id,'licencia');
assert.throws(()=>confirmPayment(debts,[],'Yape'));
assert.throws(()=>confirmPayment(debts,['licencia'],'Yape'));
assert.throws(()=>confirmPayment(debts,['predial'],'Otro'));
assert.throws(()=>confirmPayment(debts,['predial','predial'],'Yape'));
const first=confirmPayment(debts,['predial'],'Yape');
assert.equal(first.receipt.total,420);
assert.equal(debtTotal(outstanding(first.debts)),427.5);
assert.equal(visibleDebts(first.debts,'Vencido').length,0);
assert.equal(debts[0].status,'Vencido');
assert.throws(()=>confirmPayment(first.debts,['predial'],'Yape'));
const second=confirmPayment(first.debts,['arbitrios-1','arbitrios-2'],'Tarjeta',2);
assert.equal(debtTotal(outstanding(second.debts)),0);
assert.notEqual(first.receipt.reference,second.receipt.reference);
assert.match(receiptHtml(first.receipt),/S\/ 420.00/);
assert.match(receiptHtml(first.receipt),/no tiene validez tributaria/);
assert.equal(debtTotal(outstanding(initialDebts())),847.5);
console.log('OK: selección, filtros, pagos simulados, saldo, constancia y reinicio.');
